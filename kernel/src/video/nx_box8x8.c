bool nx_box_glyph_from_codepoint(uint32_t codepoint, enum nx_box_glyph *out) {
  switch (codepoint) {
  case 0x2502: *out = NX_BOX_V; return true; /* │ */
  case 0x2500: *out = NX_BOX_H; return true; /* ─ */
  case 0x250C: *out = NX_BOX_DR; return true; /* ┌ */
  case 0x2510: *out = NX_BOX_DL; return true; /* ┐ */
  case 0x2514: *out = NX_BOX_UR; return true; /* └ */
  case 0x2518: *out = NX_BOX_UL; return true; /* ┘ */
  case 0x251C: *out = NX_BOX_VR; return true; /* ├ */
  case 0x2524: *out = NX_BOX_VL; return true; /* ┤ */
  case 0x252C: *out = NX_BOX_HD; return true; /* ┬ */
  case 0x2534: *out = NX_BOX_HU; return true; /* ┴ */
  case 0x253C: *out = NX_BOX_VH; return true; /* ┼ */
  case 0x2551: *out = NX_BOX_DBL_V; return true; /* ║ */
  case 0x2550: *out = NX_BOX_DBL_H; return true; /* ═ */
  case 0x2554: *out = NX_BOX_DBL_DR; return true; /* ╔ */
  case 0x2557: *out = NX_BOX_DBL_DL; return true; /* ╗ */
  case 0x255A: *out = NX_BOX_DBL_UR; return true; /* ╚ */
  case 0x255D: *out = NX_BOX_DBL_UL; return true; /* ╝ */
  case 0x2560: *out = NX_BOX_DBL_VR; return true; /* ╠ */
  case 0x2563: *out = NX_BOX_DBL_VL; return true; /* ╣ */
  case 0x2566: *out = NX_BOX_DBL_HD; return true; /* ╦ */
  case 0x2569: *out = NX_BOX_DBL_HU; return true; /* ╩ */
  case 0x256C: *out = NX_BOX_DBL_VH; return true; /* ╬ */
  default:
    return false;
  }
}

